/** 取错误码对应的中文文案；未知错误码回退到通用提示。 */
export function errorMessage(code: string | null | undefined): string {
  if (code && code in ERROR_MESSAGES) {
    return ERROR_MESSAGES[code as ErrorCode];
  }
  return '操作失败，请稍后再试';
}